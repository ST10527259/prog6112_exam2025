// --- 1. LOAD PRODUCT DATA ---
    private void loadProductData() {
        int totalSales = logic.GetTotalSales();
        double avgSales = logic.GetAverageSales();
        int overLimit = logic.GetSalesOverLimit();
        int underLimit = logic.GetSalesUnderLimit();
        int yearsProcessed = logic.GetProductsProcessed();

        StringBuilder sb = new StringBuilder();
        sb.append("Total Sales: ").append(totalSales).append("\n");
        sb.append("Average Sales: ").append(Math.round(avgSales)).append("\n");
        sb.append("Sales over limit: ").append(overLimit).append("\n");
        sb.append("Sales under limit: ").append(underLimit);

        txtReport.setText(sb.toString());
        lblYearsProcessed.setText("Years Processed: " + yearsProcessed);
    }

    // --- 2. SAVE PRODUCT DATA TO FILE ---
    private void saveProductData() {
        String content = txtReport.getText().trim();
        if (content.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No data to save! Load product data first.",
                    "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try (java.io.BufferedWriter writer = new java.io.BufferedWriter(new java.io.FileWriter("data.txt"))) {
            writer.write("DATA LOG\n");
            writer.write("***********************************\n");
            writer.write(content + "\n");
            writer.write("***********************************");
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Data saved to data.txt successfully!",
                    "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error writing file: " + ex.getMessage(),
                    "File Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    // --- 3. CLEAR FIELDS ---
    private void clearFields() {
        txtReport.setText("");
        lblYearsProcessed.setText("Years Processed: ");
    }

